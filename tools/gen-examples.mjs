// Bundles the example programs into web/js/examples.js so the static site
// can offer them without fetching. Run after editing anything in programs/.
//   node tools/gen-examples.mjs          write the file
//   node tools/gen-examples.mjs --check  exit 1 if the file is out of date (CI)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const sets = {
  sap1: ['examples', 'tests'],
  rv32i: ['examples', 'tests', 'bugs'],
};

const out = {};
for (const [cpu, dirs] of Object.entries(sets)) {
  out[cpu] = [];
  for (const d of dirs) {
    const dir = path.join(root, 'programs', cpu, d);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.s')).sort()) {
      const source = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n');
      // First comment line is the description.
      const first = source.split('\n').find((l) => /^\s*[;#]/.test(l)) || '';
      out[cpu].push({ group: d, name: f.replace(/\.s$/, ''), title: first.replace(/^\s*[;#]\s*/, ''), source });
    }
  }
}

const text = '// Generated by tools/gen-examples.mjs from programs/. Do not edit.\n' +
  `export const EXAMPLES = ${JSON.stringify(out, null, 1)};\n`;
const file = path.join(root, 'web/js/examples.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur !== text) { console.error('web/js/examples.js is out of date: run node tools/gen-examples.mjs'); process.exit(1); }
  console.log('examples.js up to date');
} else {
  fs.writeFileSync(file, text);
  console.log(`wrote ${Object.values(out).flat().length} examples`);
}
